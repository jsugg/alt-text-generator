const REPO = 'jsugg/alt-text-generator';
const CLEAN_EMAIL = 'juanpedrosugg@gmail.com';

/**
 * @param {string} sha
 * @param {string} message
 * @param {{ author?: string, committer?: string }} [emails]
 */
const apiCommit = (sha, message, emails = {}) => ({
  sha,
  commit: {
    message,
    author: { email: emails.author ?? CLEAN_EMAIL },
    committer: { email: emails.committer ?? CLEAN_EMAIL },
  },
});

const PAGES = Symbol('pages');

/** @param {unknown[][]} pages */
const paged = (pages) => ({ [PAGES]: pages });

/**
 * @param {Record<string, any>} routes request path (without query) -> payload or paged(...)
 * @returns {jest.Mock}
 */
const fakeApi = (routes) => jest.fn(async (requestPath) => {
  const [base, query = ''] = requestPath.split('?');
  const route = routes[base];

  if (route === undefined) {
    throw new Error(`unexpected request ${requestPath}`);
  }

  if (route && route[PAGES]) {
    const page = Number(new URLSearchParams(query).get('page'));

    return route[PAGES][page - 1] ?? [];
  }

  return route;
});

describe('Unit | Scripts | GitHub | Attribution Guard', () => {
  describe('patterns', () => {
    it('lifts the inline flag prefix into RegExp flags', () => {
      expect(REF_NAME.startsWith('(?i)')).toBe(true);
      expect(COMMIT_MESSAGE.startsWith('(?im)')).toBe(true);
      expect(EMAIL.startsWith('(?i)')).toBe(true);
      expect(LABEL.startsWith('(?i)')).toBe(true);
      expect(REF_NAME_RE.flags).toBe('i');
      expect(COMMIT_MESSAGE_RE.flags).toBe('im');
      expect(EMAIL_RE.flags).toBe('i');
      expect(LABEL_RE.flags).toBe('i');
      expect(toRegExp('a+').source).toBe('a+');
    });

    it.each(GOLDEN.ref_deny)('REF_NAME denies %j', (value) => {
      expect(REF_NAME_RE.test(value)).toBe(true);
    });

    it.each(GOLDEN.ref_allow)('REF_NAME allows %j', (value) => {
      expect(REF_NAME_RE.test(value)).toBe(false);
    });

    it.each(GOLDEN.msg_deny)('COMMIT_MESSAGE denies %j', (value) => {
      expect(COMMIT_MESSAGE_RE.test(value)).toBe(true);
    });

    it.each(GOLDEN.msg_allow)('COMMIT_MESSAGE allows %j', (value) => {
      expect(COMMIT_MESSAGE_RE.test(value)).toBe(false);
    });

    it.each(GOLDEN.email_deny)('EMAIL denies %j', (value) => {
      expect(EMAIL_RE.test(value)).toBe(true);
    });

    it.each(GOLDEN.email_allow)('EMAIL allows %j', (value) => {
      expect(EMAIL_RE.test(value)).toBe(false);
    });

    it.each(['Codex-review', 'needs-claude', 'OpenAI'])('LABEL denies %j', (value) => {
      expect(LABEL_RE.test(value)).toBe(true);
    });

    it.each(['dependencies', 'security', 'github_actions'])('LABEL allows %j', (value) => {
      expect(LABEL_RE.test(value)).toBe(false);
    });
  });

  describe('findPullRequestViolations', () => {
    const cleanPullRequest = {
      number: 7,
      title: 'fix(provider): handle timeout',
      body: 'Adds a retry.',
      headRef: 'fix/provider-timeout',
      labels: ['dependencies'],
    };

    it('passes clean metadata and commits, including bot commits', () => {
      expect(findPullRequestViolations(cleanPullRequest, [{
        sha: 'a'.repeat(40),
        message: GOLDEN.msg_allow[3],
        authorEmail: GOLDEN.email_allow[1],
        committerEmail: 'noreply@github.com',
      }])).toEqual([]);
    });

    it('names every offending field', () => {
      const violations = findPullRequestViolations({
        ...cleanPullRequest,
        title: GOLDEN.msg_deny[3],
        body: GOLDEN.msg_deny[5],
        headRef: GOLDEN.ref_deny[0],
        labels: ['dependencies', 'codex'],
      }, [{
        sha: 'b'.repeat(40),
        message: GOLDEN.msg_deny[0],
        authorEmail: GOLDEN.email_deny[0],
        committerEmail: GOLDEN.email_deny[1],
      }]);

      expect(violations.map(({ field, rule }) => `${field} ${rule}`)).toEqual([
        'pull request #7 title COMMIT_MESSAGE',
        'pull request #7 body COMMIT_MESSAGE',
        'pull request #7 head ref REF_NAME',
        'pull request #7 label "codex" LABEL',
        'commit bbbbbbbbbbbb message COMMIT_MESSAGE',
        'commit bbbbbbbbbbbb author email EMAIL',
        'commit bbbbbbbbbbbb committer email EMAIL',
      ]);
    });

    it('tolerates commits without recorded emails', () => {
      expect(findCommitViolations({
        sha: 'c'.repeat(40), message: 'fix: x', authorEmail: null, committerEmail: null,
      })).toEqual([]);
    });
  });

  describe('API loading', () => {
    it('refetches the pull request and paginates every commit page', async () => {
      const firstPage = Array.from({ length: 100 }, (_, index) => (
        apiCommit(`${index}`.padStart(40, '0'), 'fix: clean')
      ));
      const apiGet = fakeApi({
        [`/repos/${REPO}/pulls/9`]: {
          title: 'chore: x',
          body: null,
          head: { ref: 'chore/x' },
          labels: [{ name: 'dependencies' }],
        },
        [`/repos/${REPO}/pulls/9/commits`]: paged([firstPage, [apiCommit('f'.repeat(40), 'fix: last')]]),
      });

      const { pullRequest, commits } = await loadPullRequest(apiGet, REPO, 9);

      expect(pullRequest).toEqual({
        number: 9, title: 'chore: x', body: '', headRef: 'chore/x', labels: ['dependencies'],
      });
      expect(commits).toHaveLength(101);
      expect(apiGet).toHaveBeenCalledWith(`/repos/${REPO}/pulls/9/commits?per_page=100&page=2`);
    });

    it('reads pushed commits from the compare range', async () => {
      const apiGet = fakeApi({
        [`/repos/${REPO}/compare/aaa...bbb`]: { commits: [apiCommit('b'.repeat(40), 'fix: y')] },
      });

      await expect(loadPushedCommits(apiGet, REPO, 'aaa', 'bbb')).resolves.toEqual([{
        sha: 'b'.repeat(40), message: 'fix: y', authorEmail: CLEAN_EMAIL, committerEmail: CLEAN_EMAIL,
      }]);
    });

    it('reads only the head commit when the push has no previous revision', async () => {
      const apiGet = fakeApi({
        [`/repos/${REPO}/commits/bbb`]: apiCommit('b'.repeat(40), 'fix: first'),
      });

      await expect(loadPushedCommits(apiGet, REPO, '0'.repeat(40), 'bbb')).resolves.toHaveLength(1);
    });
  });

  describe('main', () => {
    /** @param {Record<string, string>} env */
    const run = async (env, apiGet) => {
      const lines = [];
      const code = await main(env, apiGet, (line) => lines.push(line));

      return { code, lines };
    };

    it('passes a clean pull request', async () => {
      const apiGet = fakeApi({
        [`/repos/${REPO}/pulls/3`]: { title: 'fix: a', body: '', head: { ref: 'fix/a' }, labels: [] },
        [`/repos/${REPO}/pulls/3/commits`]: paged([[apiCommit('a'.repeat(40), 'fix: a')]]),
      });

      await expect(run({
        GITHUB_EVENT_NAME: 'pull_request', GITHUB_REPOSITORY: REPO, PR_NUMBER: '3',
      }, apiGet)).resolves.toEqual({
        code: 0,
        lines: ['Attribution Guard OK: pull request #3 (1 commit(s))'],
      });
    });

    it('fails a push whose commit carries attribution and escapes the annotation', async () => {
      const apiGet = fakeApi({
        [`/repos/${REPO}/compare/aaa...bbb`]: {
          commits: [apiCommit('b'.repeat(40), GOLDEN.msg_deny[0])],
        },
      });

      const { code, lines } = await run({
        GITHUB_EVENT_NAME: 'push',
        GITHUB_REPOSITORY: REPO,
        GITHUB_REF: 'refs/heads/main',
        PUSH_BEFORE: 'aaa',
        PUSH_AFTER: 'bbb',
      }, apiGet);

      expect(code).toBe(1);
      expect(lines[0]).toBe('Attribution Guard FAILED: push to refs/heads/main (1 commit(s))');
      expect(lines).toHaveLength(2);
      expect(lines[1]).toMatch(/^::error::commit bbbbbbbbbbbb message matches COMMIT_MESSAGE: "/u);
      expect(lines[1]).not.toMatch(/[\r\n]/u);
    });

    it('escapes matched user content in the annotation', async () => {
      const apiGet = fakeApi({
        [`/repos/${REPO}/pulls/4`]: {
          title: 'Co-authored-by: a%0A::warning::b via codex',
          body: '',
          head: { ref: 'fix/a' },
          labels: [],
        },
        [`/repos/${REPO}/pulls/4/commits`]: paged([[]]),
      });

      const { code, lines } = await run({
        GITHUB_EVENT_NAME: 'pull_request', GITHUB_REPOSITORY: REPO, PR_NUMBER: '4',
      }, apiGet);

      expect(code).toBe(1);
      expect(lines[1]).toBe(
        '::error::pull request #4 title matches COMMIT_MESSAGE: '
        + '"Co-authored-by: a%250A::warning::b via codex"',
      );
    });

    it('rejects unsupported events instead of passing silently', async () => {
      await expect(run({
        GITHUB_EVENT_NAME: 'pull_request_target', GITHUB_REPOSITORY: REPO,
      }, fakeApi({}))).rejects.toThrow('Unsupported event: pull_request_target');
    });
  });

  describe('workflow', () => {
    const workflow = /** @type {any} */ (yaml.load(fs.readFileSync(
      path.join(__dirname, '../../../../.github/workflows/attribution-guard.yml'),
      'utf8',
    )));
    const policy = JSON.parse(fs.readFileSync(
      path.join(__dirname, '../../../../config/github/required-checks.json'),
      'utf8',
    ));

    it('re-evaluates on every metadata event and audits pushes to main', () => {
      expect(Object.keys(workflow.on).sort()).toEqual(['pull_request', 'push']);
      expect(workflow.on.pull_request.types).toEqual([
        'opened', 'reopened', 'synchronize', 'edited', 'labeled', 'unlabeled', 'ready_for_review',
      ]);
      expect(workflow.on.pull_request.paths).toBeUndefined();
      expect(workflow.on.pull_request.branches).toBeUndefined();
      expect(workflow.on.push).toEqual({ branches: ['main'] });
      expect(workflow.permissions).toEqual({ contents: 'read', 'pull-requests': 'read' });
    });

    it('publishes one unconditional, required Attribution Guard check', () => {
      const jobs = Object.values(workflow.jobs);

      expect(jobs).toHaveLength(1);
      expect(jobs[0].name).toBe('Attribution Guard');
      expect(jobs[0].if).toBeUndefined();
      expect(jobs[0].steps.filter((step) => step.uses?.startsWith('actions/checkout@'))
        .every((step) => step.with['persist-credentials'] === false)).toBe(true);
      expect(policy.mainBranchProtection.contexts).toContain('Attribution Guard');
    });
  });
});
